CREATE TABLE IF NOT EXISTS fb_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,email VARCHAR(190) NOT NULL UNIQUE,password_hash VARCHAR(255) NOT NULL,
 failed_attempts INT NOT NULL DEFAULT 0,locked_until DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_occurrences (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 placa VARCHAR(40) NOT NULL,veiculo VARCHAR(255) NOT NULL,ano_modelo VARCHAR(60) NOT NULL DEFAULT '',cor VARCHAR(80) NOT NULL DEFAULT '',
 data_evento DATE NULL,data_original VARCHAR(80) NOT NULL DEFAULT '',boletim VARCHAR(255) NOT NULL DEFAULT '',municipio VARCHAR(255) NOT NULL DEFAULT '',
 vitima VARCHAR(255) NOT NULL DEFAULT '',associacao VARCHAR(255) NOT NULL DEFAULT '',evento VARCHAR(40) NOT NULL DEFAULT 'Não informado',
 situacao VARCHAR(80) NOT NULL DEFAULT 'Não informada',relatorio TEXT NULL,investigacao TEXT NULL,solucao VARCHAR(255) NOT NULL DEFAULT '',
 etapa VARCHAR(40) NOT NULL DEFAULT 'Registrado',observacoes TEXT NULL,original_json LONGTEXT NULL,avisos_json TEXT NULL,
 source_key CHAR(64) NULL UNIQUE,content_hash CHAR(64) NOT NULL,revision INT NOT NULL DEFAULT 1,
 criado_por BIGINT UNSIGNED NOT NULL,atualizado_por BIGINT UNSIGNED NOT NULL,criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_fb_data(data_evento),INDEX idx_fb_placa(placa),INDEX idx_fb_etapa(etapa),INDEX idx_fb_tipo(evento),INDEX idx_fb_hash(content_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,occurrence_id BIGINT UNSIGNED NOT NULL,user_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL,changes_json LONGTEXT NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_fb_hist(occurrence_id,id),FOREIGN KEY (occurrence_id) REFERENCES fb_occurrences(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_imports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,file_hash CHAR(64) NOT NULL,filename VARCHAR(255) NOT NULL,
 total INT NOT NULL,inserted INT NOT NULL,updated INT NOT NULL,skipped INT NOT NULL,user_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_fb_file(file_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_chat (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,question TEXT NOT NULL,answer TEXT NOT NULL,
 filters_json TEXT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_fb_chat(user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_settings (setting_key VARCHAR(100) PRIMARY KEY,setting_value TEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_conversations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,title VARCHAR(120) NOT NULL,
 legacy_owner BIGINT UNSIGNED NULL UNIQUE,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_fb_conversation_user(user_id,updated_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fb_conversation_messages (
 conversation_id BIGINT UNSIGNED NOT NULL,message_id BIGINT UNSIGNED NOT NULL UNIQUE,
 PRIMARY KEY(conversation_id,message_id),
 FOREIGN KEY(conversation_id) REFERENCES fb_conversations(id) ON DELETE CASCADE,
 FOREIGN KEY(message_id) REFERENCES fb_chat(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
